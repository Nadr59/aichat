package com.example.aichat.repository

import com.example.aichat.data.model.MemoryItem

object MemoryCuratorPrompt {

    /**
     * بناء برومبت الوسيط الذكي.
     *
     * الدور المزدوج:
     * 1. تنقية سياق الذاكرة (السلوك الأصلي، فعّال دائماً إن وُجدت [candidates]).
     * 2. إن وُجد [mediatorIdentityText]، يتحول الوسيط أيضاً لمحسّن طلبات:
     *    يقترح نقاط محتوى ملموسة تخدم هذه الهوية.
     *
     * قاعدة صارمة غير قابلة للتفاوض:
     * سؤال المستخدم لا يُعاد صياغته ولا يُستبدل أبداً هنا — هذا الملف ينتج
     * فقط كتلة سياق/توجيه مرافقة. النموذج المُجيب سيتلقى السؤال الأصلي
     * حرفياً من طبقة أعلى (ChatRepository)، بصرف النظر عن مخرجات هذا البرومبت.
     */
    fun build(
        userQuery: String,
        candidates: List<MemoryItem>,
        mediatorIdentityText: String = ""
    ): String = buildString {

        appendLine("أنت وسيط ذاكرة متخصص. مهمتك تجهيز كتلة سياق/توجيه موجزة تُرسَل مع سؤال المستخدم لنموذج آخر (النموذج المُجيب).")
        appendLine("أنت لست من سيُجيب على السؤال، ولا تحاول الإجابة عليه بنفسك بأي شكل.")
        appendLine()
        appendLine("قاعدة صارمة: سؤال المستخدم أدناه سيُرسَل حرفياً كما هو دائماً للنموذج المُجيب،")
        appendLine("بصرف النظر عمّا تكتبه أنت. لا تُعِد صياغته، لا تستبدله، لا تُلخّصه، ولا تُجب عليه.")
        appendLine()
        appendLine("سؤال المستخدم الحالي:")
        appendLine("\"$userQuery\"")

        if (candidates.isNotEmpty()) {
            appendLine()
            appendLine("ذكريات مخزّنة (قد يتكرر بعضها أو لا صلة له):")
            candidates.forEachIndexed { i, m ->
                appendLine("${i + 1}. [${m.category}] ${m.content.take(300)}")
            }
        }

        if (mediatorIdentityText.isNotBlank()) {
            appendLine()
            appendLine(
                """
                مهمتك الإضافية: بناءً على وصف الهوية/الأسلوب التالي الذي حدّده المستخدم:
                "$mediatorIdentityText"

                اقترح من 2 إلى 4 نقاط محتوى ملموسة ومحددة (وليست صفات أسلوب عامة مجردة)
                يجب أن تغطيها الإجابة على السؤال أعلاه كي تخدم هذه الهوية فعلياً.

                مثال على الفرق المطلوب فهمه:
                  ضعيف (تجنّب هذا النوع تماماً): "أجب بأسلوب تقني" أو "كن رسمياً"
                  قوي (اطلب هذا النوع فقط): "أضف مثال كود قصير"، "اذكر التعقيد الزمني للخوارزمية"،
                     "نبّه لحالة الحافة كذا"، "اربط الفكرة بمثال هندسي عملي"

                إن لم يكن الوصف واضحاً بما يكفي لاستنتاج نقاط ملموسة فعلية، تجاهل هذا القسم
                كلياً بدل اختلاق نقاط عامة غير مفيدة.
                """.trimIndent()
            )
        }

        appendLine()
        appendLine("التعليمات النهائية للإخراج:")

        if (candidates.isNotEmpty()) {
            appendLine("- استخلص فقط ما له صلة فعلية ومباشرة بالسؤال من الذكريات أعلاه")
            appendLine("- ادمج الذكريات المتشابهة في نقطة واحدة موجزة")
            appendLine("- تجاهل تماماً ما لا صلة له")
        }

        appendLine("- أخرج النتيجة كنقاط مختصرة مباشرة، بلا مقدمات أو شرح")
        appendLine("- لا تُضف عناوين أو زخرفة، فقط النقاط نفسها")

        if (mediatorIdentityText.isNotBlank() && candidates.isNotEmpty()) {
            appendLine("- إن أخرجت نقاط سياق ونقاط هوية معاً، افصل بينهما بوضوح (كل نوع في سطوره)")
        }

        appendLine("- إذا لم يوجد أي شيء ذو صلة فعلية (لا سياق ولا نقاط هوية قابلة للاستنتاج)، أخرج فقط الكلمة: NONE")
    }
}
