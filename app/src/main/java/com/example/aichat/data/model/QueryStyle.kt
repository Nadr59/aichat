package com.example.aichat.data.model

/**
 * أنماط تحسين صياغة السؤال (بدون إضافة محتوى)
 */
enum class QueryStyle(
    val emoji: String,
    val displayName: String,
    val description: String
) {
    FORMAL(
        emoji = "📋",
        displayName = "رسمي",
        description = "لغة فصحى راقية مناسبة للمراسلات الرسمية"
    ),
    
    CASUAL(
        emoji = "💬",
        displayName = "عامي",
        displayName = "لغة بسيطة ومباشرة كأنك تتحدث مع صديق"
    ),
    
    ACADEMIC(
        emoji = "📚",
        displayName = "أكاديمي",
        description = "أسلوب علمي بحثي مع مصطلحات دقيقة"
    ),
    
    CREATIVE(
        emoji = "🎨",
        displayName = "إبداعي",
        description = "أسلوب أدبي جذاب مع استعارات وتشبيهات"
    );
    
    /**
     * بناء prompt تحسين الصياغة لهذا النمط
     */
    fun buildPrompt(userQuery: String): String = when (this) {
        FORMAL -> """
أعد صياغة السؤال التالي بأسلوب رسمي راقٍ:

القواعد:
1. استخدم لغة فصحى دقيقة ومهذبة
2. تجنب العامية تماماً
3. احتفظ بنفس المعنى بالضبط
4. لا تضف معلومات أو تفاصيل لم تُذكر
5. لا تغير نطاق السؤال

السؤال الأصلي:
"$userQuery"

أعد صياغته رسمياً فقط (بدون شرح أو مقدمات):
        """.trimIndent()
        
        CASUAL -> """
أعد صياغة السؤال التالي بلغة عامية بسيطة:

القواعد:
1. استخدم لغة الشارع العادية
2. كن طبيعياً ومباشراً
3. احتفظ بنفس المعنى
4. لا تضف معلومات جديدة
5. اجعله كأن صديق يسأل صديقه

السؤال الأصلي:
"$userQuery"

أعد صياغته بالعامية فقط:
        """.trimIndent()
        
        ACADEMIC -> """
أعد صياغة السؤال التالي بأسلوب أكاديمي علمي:

القواعد:
1. استخدم مصطلحات علمية دقيقة
2. صِغه كسؤال بحثي محترف
3. احتفظ بنفس الموضوع بالضبط
4. لا تضف فرضيات أو متغيرات جديدة
5. ليكن مناسباً لورقة بحثية

السؤال الأصلي:
"$userQuery"

أعد صياغته أكاديمياً فقط:
        """.trimIndent()
        
        CREATIVE -> """
أعد صياغة السؤال التالي بأسلوب أدبي إبداعي:

القواعد:
1. استخدم استعارات وتشبيهات جميلة
2. اجعله جذاباً وفنياً
3. احتفظ بالمعنى الأساسي
4. لا تغير طبيعة السؤال أو نطاقه
5. أضف جمالية لغوية بدون مبالغة

السؤال الأصلي:
"$userQuery"

أعد صياغته بأسلوب إبداعي فقط:
        """.trimIndent()
    }
}
